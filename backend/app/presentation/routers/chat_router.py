"""API router exposing interactive AI Assistant endpoints with streaming support."""

import json
from typing import AsyncGenerator
from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse

from app.presentation.dependencies import get_chat_use_case
from app.application.dtos.chat_dto import (
    ChatQueryRequestDTO,
    ChatResponseDTO,
)
from app.application.use_cases.chat_use_cases import LangGraphRAGChatUseCase
from app.domain.entities.chat_session import ChatMessage, ChatRole

router = APIRouter(prefix="/chat", tags=["AI Assistant Chat"])


@router.post(
    "/message",
    response_model=ChatResponseDTO,
    summary="Submit query to AI Assistant for synchronous response",
)
async def chat_message(
    payload: ChatQueryRequestDTO,
    use_case: LangGraphRAGChatUseCase = Depends(get_chat_use_case),
):
    """Processes user query through LangGraph RAG pipeline and returns synchronous response."""
    history = [
        ChatMessage(
            role=ChatRole.USER if msg.role == "user" else ChatRole.ASSISTANT,
            content=msg.content,
        )
        for msg in payload.history
    ]

    return await use_case.execute_sync(
        session_id=payload.session_id,
        query=payload.message,
        history=history,
    )


@router.post(
    "/stream",
    summary="Stream conversational response tokens using Server-Sent Events (SSE)",
)
async def chat_stream(
    payload: ChatQueryRequestDTO,
    use_case: LangGraphRAGChatUseCase = Depends(get_chat_use_case),
):
    """Streams conversational response tokens generated by Gemini RAG pipeline via SSE."""
    history = [
        ChatMessage(
            role=ChatRole.USER if msg.role == "user" else ChatRole.ASSISTANT,
            content=msg.content,
        )
        for msg in payload.history
    ]

    async def sse_token_generator() -> AsyncGenerator[str, None]:
        try:
            async for token in use_case.execute_stream(
                session_id=payload.session_id,
                query=payload.message,
                history=history,
            ):
                payload_json = json.dumps({"token": token})
                yield f"data: {payload_json}\n\n"
        except Exception as exc:
            error_json = json.dumps({"error": str(exc)})
            yield f"data: {error_json}\n\n"
        finally:
            yield "data: [DONE]\n\n"

    return StreamingResponse(
        sse_token_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )
